// Embed local texture sources so file:// previews remain origin-clean for WebGL and export.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const sources = ['wood', 'fire', 'earth', 'metal', 'water'].map(name =>
  'data:image/png;base64,' + fs.readFileSync(path.join(root, 'assets/elements-v2', name + '.png')).toString('base64'));
fs.writeFileSync(path.join(root, 'element-pattern-data.js'), '/* Generated by scripts/bundle-element-patterns.cjs */\nwindow.ElementPatternSources=' + JSON.stringify(sources) + ';\n');
